/**
 * pnpm repro — regenerate every number in report/ from committed inputs:
 *   1. vault:build       (data/vault/funds/* from committed universe.json)
 *   2. planner:fixtures  (report/planner-fixtures.json)
 *   3. eval              (report/fund-qa.json, report/latency.txt; live probes only if dev server up)
 *   4. report/manifest.json (inputs used + timestamps + counts)
 * Deterministic steps need no network or keys beyond what build needs.
 */
import { execSync } from "node:child_process";
import { readdirSync, statSync, writeFileSync } from "node:fs";

const step = (name: string, cmd: string) => {
  console.log(`\n== ${name}`);
  execSync(cmd, { stdio: "inherit" });
};

async function main() {
  step("vault:build", "pnpm exec tsx scripts/vault-build.ts");
  step("planner:fixtures", "pnpm exec tsx scripts/planner-fixtures.ts");
  step("eval", "pnpm exec tsx scripts/eval.ts");

  const files = readdirSync("report").filter((f) => !f.endsWith("manifest.json") && f !== "README.md");
  const manifest = {
    generatedAt: new Date().toISOString(),
    note: "regenerated by `pnpm repro` — every report number traces to committed inputs",
    inputs: [
      "data/vault/universe.json (AMFI NAVAll 2026-10-28)",
      "data/personas/personas.json (SYNTHETIC)",
      "data/policy/assumptions.json (adviser-editable, illustrative)",
      "src/lib/planner, src/lib/gates (deterministic)",
    ],
    artifacts: files.map((f) => ({ file: `report/${f}`, bytes: statSync(`report/${f}`).size })),
  };
  writeFileSync("report/manifest.json", JSON.stringify(manifest, null, 2) + "\n");
  console.log(`\nmanifest -> report/manifest.json (${files.length} artifacts)`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
